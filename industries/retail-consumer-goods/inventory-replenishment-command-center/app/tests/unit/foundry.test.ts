import { describe, expect, it } from "vitest";
import { calculateException } from "../../src/server/calculations.js";
import { createSeedData } from "../../src/server/data/seed.js";
import {
  FoundryAgentInvoker,
  PROMOTION_NON_CAUSATION_CAVEAT,
  hasUnsupportedPromotionCausation,
  validateInvestigationOutput,
  validateRecommendationOutput,
} from "../../src/server/foundry.js";
import { generateOptions } from "../../src/server/options.js";
import { initialState } from "../../src/server/state.js";
import { loadConfig } from "../../src/server/config.js";

describe("Foundry boundaries", () => {
  const data = createSeedData();
  const state = initialState();
  const exception = calculateException(data, state, "store-01", "HL-KNT-EVD-FGN-M");
  const options = generateOptions(data, state, exception);
  const cork = options.find(
    (option) => option.type === "store-transfer" && option.sourceLocationId === "store-02",
  )!;

  function canonicalCount(value: unknown): number {
    return JSON.stringify(value).split(PROMOTION_NON_CAUSATION_CAVEAT).length - 1;
  }

  it("accepts grounded schema-valid outputs", () => {
    const result = validateInvestigationOutput(
      {
        summary: "Low cover precedes the scheduled delivery.",
        evidenceIds: [exception.evidence[0]!.id],
        caveats: [],
      },
      exception.evidence,
    );
    expect(result.status).toBe("available");
    expect(result.summary).toBe("Low cover precedes the scheduled delivery.");
    expect(result.caveats).toContain(PROMOTION_NON_CAUSATION_CAVEAT);
    expect(canonicalCount(result)).toBe(1);
  });

  it.each([
    "The promotion caused the shortage.",
    "The campaign causes higher demand.",
    "The edit is causing the exception.",
    "The promotion drove demand.",
    "The campaign drives sales.",
    "The edit has driven the stockout.",
    "The promotion led to the shortage.",
    "The campaign leads to higher sales.",
    "The edit is leading to the exception.",
    "The promotion resulted in low cover.",
    "The campaign results in higher demand.",
    "The edit is resulting in the shortage.",
    "The shortage resulted from the promotion.",
    "The promotion triggered the stockout.",
    "The campaign triggers demand.",
    "The edit is triggering the exception.",
    "The promotion boosted sales.",
    "The campaign boosts demand.",
    "The edit is boosting sales.",
    "Demand increased due to the promotion.",
    "The shortage happened because of the campaign.",
    "Sales were triggered by the promotions.",
    "Low cover was boosted by seasonal campaigns.",
  ])("neutralizes the causal phrase family in summaries: %s", (summary) => {
    const result = validateInvestigationOutput(
      {
        summary,
        evidenceIds: exception.evidence.map((item) => item.id),
        caveats: [],
      },
      exception.evidence,
    );
    expect(result.summary).toBe("Promotion appears in the supplied evidence as a signal.");
    expect(canonicalCount(result)).toBe(1);
  });

  const newlyRejectedCausalPhrases = [
    "The promotion contributed to the shortage.",
    "The campaign contributes toward higher demand.",
    "The edit may have contributed towards the exception.",
    "The promotion is contributing to the shortage.",
    "The shortage was attributed to the promotion.",
    "Higher demand is attributable partly to the campaign.",
    "The model is attributing the stockout to the edit.",
    "The promotion created the shortage.",
    "The campaign may have created higher demand.",
    "The promotion was creating an availability risk.",
    "The stockout was created by the edit.",
    "The promotion generated higher demand.",
    "The campaign has been generating revenue.",
    "Sales were generated by the seasonal campaign.",
    "The campaign explains the shortage.",
    "The edit may explain higher demand.",
    "The campaign is explaining the sales increase.",
    "The stockout was explained by the promotion.",
  ];

  it.each(
    newlyRejectedCausalPhrases.flatMap((text) => [
      ["investigation summary", text],
      ["investigation caveat", text],
      ["recommendation summary", text],
      ["recommendation tradeoff", text],
    ]),
  )("neutralizes newly rejected families in every generated field: %s — %s", (field, text) => {
    const evidenceIds = exception.evidence.map((item) => item.id);
    if (field === "investigation summary") {
      const result = validateInvestigationOutput(
        { summary: text, evidenceIds, caveats: ["Keep this caveat."] },
        exception.evidence,
      );
      expect(result.summary).toBe("Promotion appears in the supplied evidence as a signal.");
      expect(result.caveats).toContain("Keep this caveat.");
      expect(canonicalCount(result)).toBe(1);
      return;
    }
    if (field === "investigation caveat") {
      const result = validateInvestigationOutput(
        { summary: "Keep this summary.", evidenceIds, caveats: [text] },
        exception.evidence,
      );
      expect(result.summary).toBe("Keep this summary.");
      expect(result.caveats[0]).toBe("Promotion appears in the supplied evidence as a signal.");
      expect(canonicalCount(result)).toBe(1);
      return;
    }
    const recommendation = {
      summary: field === "recommendation summary" ? text : "Keep this summary.",
      selectedOptionId: cork.id,
      consideredOptionIds: [cork.id],
      evidenceIds,
      tradeoffs: field === "recommendation tradeoff" ? [text] : ["Keep this tradeoff."],
    };
    const result = validateRecommendationOutput(
      recommendation,
      exception.evidence,
      options,
      cork.id,
    );
    if (field === "recommendation summary") {
      expect(result.summary).toBe("Promotion appears in the supplied evidence as a signal.");
      expect(result.tradeoffs).toContain("Keep this tradeoff.");
    } else {
      expect(result.summary).toBe("Keep this summary.");
      expect(result.tradeoffs[0]).toBe("Promotion appears in the supplied evidence as a signal.");
    }
    expect(canonicalCount(result)).toBe(1);
  });

  it.each([
    "The promotion was created yesterday and remains scheduled.",
    "The campaign was generated from a reusable template.",
    "The campaign generated a sales report for planner review.",
    "The promotion record was created by the planning system.",
    "The edit was created to address low sales.",
    "The system generated a shortage forecast after reviewing the promotion.",
    "The campaign explains its own configuration in the attached note.",
  ])("preserves legitimate non-causal promotion context: %s", (text) => {
    expect(hasUnsupportedPromotionCausation(text)).toBe(false);
    const evidenceIds = exception.evidence.map((item) => item.id);
    const investigation = validateInvestigationOutput(
      { summary: text, evidenceIds, caveats: [text] },
      exception.evidence,
    );
    expect(investigation.summary).toBe(text);
    expect(investigation.caveats).toEqual([text, PROMOTION_NON_CAUSATION_CAVEAT]);
  });

  it("neutralizes every investigation text field while preserving grounded IDs and non-causal text", () => {
    const evidenceIds = exception.evidence.map((item) => item.id);
    const result = validateInvestigationOutput(
      {
        summary:
          "The promotion triggered the shortage, but low cover precedes the scheduled delivery.",
        evidenceIds,
        caveats: [
          "Demand was boosted because of the campaign; verify reservations before action.",
          "The Cork transfer remains feasible.",
          PROMOTION_NON_CAUSATION_CAVEAT,
          PROMOTION_NON_CAUSATION_CAVEAT,
        ],
      },
      exception.evidence,
    );
    expect(result.summary).toBe(
      "Promotion appears in the supplied evidence as a signal, but low cover precedes the scheduled delivery.",
    );
    expect(result.caveats).toEqual([
      "Promotion appears in the supplied evidence as a signal; verify reservations before action.",
      "The Cork transfer remains feasible.",
      PROMOTION_NON_CAUSATION_CAVEAT,
    ]);
    expect(result.evidenceIds).toEqual(evidenceIds);
    expect(canonicalCount(result)).toBe(1);
  });

  it("neutralizes every recommendation text field without changing evidence or options", () => {
    const evidenceIds = exception.evidence.map((item) => item.id);
    const consideredOptionIds = [cork.id];
    const result = validateRecommendationOutput(
      {
        summary: "The campaign drove demand, so use the Cork transfer.",
        selectedOptionId: cork.id,
        consideredOptionIds,
        evidenceIds,
        tradeoffs: [
          "Low cover was caused by the promotion; protect Cork donor cover.",
          "The transfer arrives before the scheduled inbound.",
        ],
      },
      exception.evidence,
      options,
      cork.id,
    );
    expect(result.summary).toBe(
      "Promotion appears in the supplied evidence as a signal, so use the Cork transfer.",
    );
    expect(result.tradeoffs).toEqual([
      "Promotion appears in the supplied evidence as a signal; protect Cork donor cover.",
      "The transfer arrives before the scheduled inbound.",
      PROMOTION_NON_CAUSATION_CAVEAT,
    ]);
    expect(result.selectedOptionId).toBe(cork.id);
    expect(result.consideredOptionIds).toEqual(consideredOptionIds);
    expect(result.evidenceIds).toEqual(evidenceIds);
    expect(canonicalCount(result)).toBe(1);
  });

  it("is idempotent and keeps exactly one canonical caveat", () => {
    const first = validateInvestigationOutput(
      {
        summary: `The promotion caused low cover. ${PROMOTION_NON_CAUSATION_CAVEAT}`,
        evidenceIds: exception.evidence.map((item) => item.id),
        caveats: [PROMOTION_NON_CAUSATION_CAVEAT],
      },
      exception.evidence,
    );
    const second = validateInvestigationOutput(
      {
        summary: first.summary,
        evidenceIds: first.evidenceIds,
        caveats: first.caveats,
      },
      exception.evidence,
    );
    expect(second).toEqual(first);
    expect(canonicalCount(second)).toBe(1);
  });

  it("preserves eight valid model caveats and adds the canonical caveat without loss", () => {
    const caveats = Array.from({ length: 8 }, (_, index) => `Valid caveat ${index + 1}.`);
    const result = validateInvestigationOutput(
      {
        summary: "Low cover precedes the scheduled delivery.",
        evidenceIds: exception.evidence.map((item) => item.id),
        caveats,
      },
      exception.evidence,
    );
    expect(result.caveats).toEqual([...caveats, PROMOTION_NON_CAUSATION_CAVEAT]);
    expect(result.caveats).toHaveLength(9);
    expect(canonicalCount(result)).toBe(1);
  });

  it("preserves eight valid model tradeoffs and adds the canonical caveat without loss", () => {
    const tradeoffs = Array.from({ length: 8 }, (_, index) => `Valid tradeoff ${index + 1}.`);
    const result = validateRecommendationOutput(
      {
        summary: "Use the grounded Cork transfer.",
        selectedOptionId: cork.id,
        consideredOptionIds: [cork.id],
        evidenceIds: exception.evidence.map((item) => item.id),
        tradeoffs,
      },
      exception.evidence,
      options,
      cork.id,
    );
    expect(result.tradeoffs).toEqual([...tradeoffs, PROMOTION_NON_CAUSATION_CAVEAT]);
    expect(result.tradeoffs).toHaveLength(9);
    expect(canonicalCount(result)).toBe(1);
  });

  it("rejects model supporting text beyond the eight-item input bound before rewriting", () => {
    const evidenceIds = exception.evidence.map((item) => item.id);
    const overBound = Array.from({ length: 9 }, (_, index) => `Item ${index + 1}.`);
    expect(() =>
      validateInvestigationOutput(
        { summary: "The promotion created the shortage.", evidenceIds, caveats: overBound },
        exception.evidence,
      ),
    ).toThrow();
    expect(() =>
      validateRecommendationOutput(
        {
          summary: "The promotion generated demand.",
          selectedOptionId: cork.id,
          consideredOptionIds: [cork.id],
          evidenceIds,
          tradeoffs: overBound,
        },
        exception.evidence,
        options,
        cork.id,
      ),
    ).toThrow();
  });

  it("does not rewrite or add a caveat when promotion evidence is absent", () => {
    const evidence = exception.evidence.filter((item) => item.kind !== "promotion");
    const summary = "A campaign caused the shortage, while low cover remains observable.";
    const caveats = ["Because of the promotion, demand increased."];
    const result = validateInvestigationOutput(
      {
        summary,
        evidenceIds: [evidence[0]!.id],
        caveats,
      },
      evidence,
    );
    expect(result.summary).toBe(summary);
    expect(result.caveats).toEqual(caveats);
    expect(result.caveats).not.toContain(PROMOTION_NON_CAUSATION_CAVEAT);
  });

  it("validates schema and grounding before any causation rewrite", () => {
    expect(() =>
      validateInvestigationOutput(
        {
          summary: "The promotion caused the shortage.",
          evidenceIds: [],
          caveats: [],
        },
        exception.evidence,
      ),
    ).toThrow();
    expect(() =>
      validateInvestigationOutput(
        {
          summary: "The promotion caused the shortage.",
          evidenceIds: ["invented"],
          caveats: [],
        },
        exception.evidence,
      ),
    ).toThrow(/outside supplied boundaries/);
    expect(() =>
      validateRecommendationOutput(
        {
          summary: "The promotion boosted demand.",
          selectedOptionId: "invented",
          consideredOptionIds: ["invented"],
          evidenceIds: [exception.evidence[0]!.id],
          tradeoffs: [],
        },
        exception.evidence,
        options,
      ),
    ).toThrow(/exceeded supplied/);
  });

  it("rejects infeasible and non-policy options without fabrication", () => {
    const wait = options.find((option) => option.type === "wait")!;
    expect(wait.feasible).toBe(false);
    expect(() =>
      validateRecommendationOutput(
        {
          summary: "Wait",
          selectedOptionId: wait.id,
          consideredOptionIds: [wait.id],
          evidenceIds: [exception.evidence[0]!.id],
          tradeoffs: [],
        },
        exception.evidence,
        options,
      ),
    ).toThrow(/infeasible/);
    const warehouse = options.find((option) => option.type === "warehouse")!;
    expect(() =>
      validateRecommendationOutput(
        {
          summary: "Wrong feasible option",
          selectedOptionId: warehouse.id,
          consideredOptionIds: [warehouse.id, cork.id],
          evidenceIds: [exception.evidence[0]!.id],
          tradeoffs: [],
        },
        exception.evidence,
        options,
        cork.id,
      ),
    ).toThrow(/policy-preferred/);
  });

  it("returns an honest unavailable result when Foundry is not configured", async () => {
    const invoker = new FoundryAgentInvoker({
      ...loadConfig("test"),
      foundryProjectEndpoint: undefined,
      foundryModelDeployment: undefined,
    });
    const result = await invoker.investigate(exception.evidence);
    expect(result.status).toBe("unavailable");
    expect(result.summary).toContain("not configured");
  });
});
